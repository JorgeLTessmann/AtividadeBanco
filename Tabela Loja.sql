     E.DATAMOVIMENTO            DATAMOVIMENTO
    ,E.QUANTIDADE               QUANTIDADE
    ,P.UNIDADEMEDIDA            UN
    ,E.VALOR                    VALORUNITARIO
    ,E.QUANTIDADE*E.VALOR       VALOR
    ,CONCAT(P.ID,'-',P.NOME)    PRODUTO
