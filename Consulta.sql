    TIME,
    SUM(PONTOS) AS PONTOSTOTAIS
FROM (
    SELECT 
        MANDANTE AS TIME,
        CASE
            WHEN MANDANTEGOLS > VISITANTEGOLS THEN 3
            WHEN MANDANTEGOLS < VISITANTEGOLS THEN 0
            ELSE 1
        END AS PONTOS
    FROM TBRAS
    
    UNION ALL
    
    SELECT 
        VISITANTE AS TIME,
        CASE
            WHEN MANDANTEGOLS > VISITANTEGOLS THEN 0
            WHEN MANDANTEGOLS < VISITANTEGOLS THEN 3
            ELSE 1
        END AS PONTOS
    FROM TBRAS2
) AS todos_times
GROUP BY TIME
ORDER BY PONTOSTOTAIS DESC;



