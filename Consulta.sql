CREATE TEMPORARY TABLE pontos AS 
SELECT 
	MANDANTE,
	MANDANTEGOLS,
	VISITANTEGOLS,
	VISITANTE,
	
	CASE
		WHEN MANDANTEGOLS > VISITANTEGOLS THEN 3
		WHEN MANDANTEGOLS < VISITANTEGOLS THEN 0
		WHEN MANDANTEGOLS = VISITANTEGOLS THEN 1
	END AS PONTOSMANDANTE,
	
	CASE
		WHEN MANDANTEGOLS > VISITANTEGOLS THEN 0
		WHEN MANDANTEGOLS < VISITANTEGOLS THEN 3
		WHEN MANDANTEGOLS = VISITANTEGOLS THEN 1
	END AS PONTOSVISITANTE
	
FROM TBRAS;

SELECT
	MANDANTE,
	SUM(PONTOSMANDANTE + PONTOSVISITANTE) AS PONTOSTOTAIS
FROM pontos
GROUP BY MANDANTE
ORDER BY PONTOSTOTAIS DESC;



